"""Turn one model blob (.aqm) into a C header, to build a model into the Sensa firmware.

    python tools/blob_to_header.py export_classical/h24/multi/heldout-Zagreb/LR.aqm -o aq_model_blob.h

The header defines ``aq_model_blob`` (16-byte aligned, in flash on the ESP32) and
``aq_model_blob_len``; load it with ``aq_load(&model, aq_model_blob, aq_model_blob_len)``.
"""
from __future__ import annotations

import argparse
import os


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("blob")
    ap.add_argument("-o", "--out", default="aq_model_blob.h")
    ap.add_argument("--name", default="aq_model_blob")
    args = ap.parse_args()
    data = open(args.blob, "rb").read()
    if data[:4] != b"AQM1":
        raise SystemExit(f"{args.blob} is not a model blob")
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    guard = os.path.basename(args.out).upper().replace(".", "_").replace("-", "_")
    with open(args.out, "w", newline="\n") as f:
        f.write(f"/* generated by tools/blob_to_header.py from {os.path.basename(args.blob)} */\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n#include <stddef.h>\n")
        f.write(f"static const uint8_t {args.name}[{len(data)}] __attribute__((aligned(16))) = {{\n")
        f.write(",\n".join("    " + r for r in rows))
        f.write(f"\n}};\nstatic const size_t {args.name}_len = {len(data)};\n#endif\n")
    print(f"{len(data)} bytes -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
